/**
 * Regenerates src/lib/letters/templates/metadata.ts — the light, eagerly
 * loaded index of which templates exist plus their evidence metadata. The
 * full templates (scaffolds, examples, constraints) are lazy-loaded per
 * letter type; see src/lib/letters/templates/index.ts.
 *
 * Run after adding or editing a template:
 *   npx tsx scripts/gen-template-metadata.ts
 *
 * src/lib/letters/templates/metadata.test.ts fails when this file is stale.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EMPLOYER_TEMPLATES } from "../src/lib/letters/templates/employer";
import { EMPLOYEE_TEMPLATES } from "../src/lib/letters/templates/employee";
import { toTemplateMetadata } from "../src/lib/letters/templates/metadata-shape";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../src/lib/letters/templates/metadata.ts");

const entries = [...EMPLOYER_TEMPLATES, ...EMPLOYEE_TEMPLATES]
  .map(([key, tpl]) => [key, toTemplateMetadata(tpl)] as const)
  .sort(([a], [b]) => a.localeCompare(b));

const body = `// GENERATED by scripts/gen-template-metadata.ts. Do not edit by hand.
import type { LetterTemplateKey } from "./types";
import type { TemplateMetadata } from "./metadata-shape";

export const TEMPLATE_METADATA: Readonly<Partial<Record<LetterTemplateKey, TemplateMetadata>>> = ${JSON.stringify(
  Object.fromEntries(entries),
  null,
  2,
)};
`;
writeFileSync(out, body);
console.log(`wrote ${entries.length} entries to ${out}`);
