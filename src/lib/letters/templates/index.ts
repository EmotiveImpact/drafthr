import type { Jurisdiction, LetterTypeId, SectionId } from "../types";
import type { EvidenceTier, LetterTemplate, SectionTemplate } from "./types";
import { templateKey } from "./types";
import { getLetterMeta } from "../catalog";

import { useSyncExternalStore } from "react";
import { TEMPLATE_METADATA } from "./metadata";
import type { TemplateMetadata } from "./metadata-shape";

/**
 * Central registry. Templates contributed by:
 *  - employer/*.ts  (17 employer letters x UK/US)
 *  - employee/*.ts  (21 employee letters x UK/US)
 *
 * Full templates are heavy (scaffolds, constraints, worked examples) and are
 * only needed when generating or scoring a specific letter, so each letter
 * type's file is its own lazily loaded chunk. Surfaces that only need to know
 * which templates exist, or their evidence checklist, read the eager
 * TEMPLATE_METADATA index (generated by scripts/gen-template-metadata.ts).
 *
 * `getTemplate` is synchronous and returns a template only once it has been
 * loaded with `loadTemplate` (or `useLetterTemplate` in React). If a template
 * isn't available, the prompt builder falls back to the generic
 * SECTION_INSTRUCTIONS pipeline at src/lib/prompts/sections.ts, so async
 * callers (generation, export) must `await loadTemplate(...)` first.
 */

type TemplateModule = Record<string, unknown>;

const LOADERS: Record<string, () => Promise<TemplateModule>> = Object.fromEntries(
  Object.entries(
    import.meta.glob<TemplateModule>([
      "./employer/*.ts",
      "./employee/*.ts",
      "!./employer/index.ts",
      "!./employee/index.ts",
    ]),
  ).map(([file, load]) => [file.replace(/^.*\/(.+)\.ts$/, "$1"), load]),
);

const CACHE = new Map<string, LetterTemplate>();
const PENDING = new Map<string, Promise<void>>();
const listeners = new Set<() => void>();
let version = 0;

function isTemplate(value: unknown): value is LetterTemplate {
  return (
    typeof value === "object" &&
    value !== null &&
    "letterType" in value &&
    "jurisdiction" in value &&
    Array.isArray((value as LetterTemplate).sections)
  );
}

function loadLetterType(letterType: LetterTypeId): Promise<void> {
  const existing = PENDING.get(letterType);
  if (existing) return existing;
  const loader = LOADERS[letterType];
  if (!loader) return Promise.resolve();
  const p = loader()
    .then((mod) => {
      for (const value of Object.values(mod)) {
        if (isTemplate(value)) CACHE.set(templateKey(value.letterType, value.jurisdiction), value);
      }
      version++;
      for (const l of listeners) l();
    })
    .catch((err) => {
      // Allow a retry on the next call (e.g. a transient chunk fetch failure).
      PENDING.delete(letterType);
      throw err;
    });
  PENDING.set(letterType, p);
  return p;
}

/** Load (once) and return the full template for a letter type x jurisdiction. */
export async function loadTemplate(
  letterType: LetterTypeId,
  jurisdiction: Jurisdiction,
): Promise<LetterTemplate | undefined> {
  if (!hasTemplate(letterType, jurisdiction)) return undefined;
  await loadLetterType(letterType);
  return CACHE.get(templateKey(letterType, jurisdiction));
}

/** Load every template. For tests and tooling; the app loads on demand. */
export async function loadAllTemplates(): Promise<void> {
  await Promise.all(Object.keys(LOADERS).map((t) => loadLetterType(t as LetterTypeId)));
}

/**
 * React hook: returns the full template once loaded (undefined until then)
 * and triggers the load. Components that score or render against template
 * constraints call this so they re-render when the chunk arrives.
 */
export function useLetterTemplate(
  letterType: LetterTypeId | undefined,
  jurisdiction: Jurisdiction | undefined,
): LetterTemplate | undefined {
  useSyncExternalStore(subscribe, getVersion, getVersion);
  if (!letterType || !jurisdiction) return undefined;
  const tpl = getTemplate(letterType, jurisdiction);
  if (!tpl && hasTemplate(letterType, jurisdiction)) {
    void loadLetterType(letterType).catch(() => {
      /* surfaced as "no template data" until a later retry */
    });
  }
  return tpl;
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function getVersion(): number {
  return version;
}

export function getTemplate(
  letterType: LetterTypeId,
  jurisdiction: Jurisdiction
): LetterTemplate | undefined {
  return CACHE.get(templateKey(letterType, jurisdiction));
}

export function getSectionTemplate(
  letterType: LetterTypeId,
  jurisdiction: Jurisdiction,
  sectionId: SectionId
): SectionTemplate | undefined {
  return getTemplate(letterType, jurisdiction)?.sections.find(
    (s) => s.sectionId === sectionId
  );
}

/** Light metadata (evidence checklist + tier); always available synchronously. */
export function getTemplateMetadata(
  letterType: LetterTypeId,
  jurisdiction: Jurisdiction
): TemplateMetadata | undefined {
  return TEMPLATE_METADATA[templateKey(letterType, jurisdiction)];
}

export function hasTemplate(
  letterType: LetterTypeId,
  jurisdiction: Jurisdiction
): boolean {
  return templateKey(letterType, jurisdiction) in TEMPLATE_METADATA;
}

/**
 * Resolve the evidence tier for a template. Returns the explicit
 * `evidenceTier` set on the template when present; otherwise derives a
 * sensible default from the letter's category and risk profile per the
 * product rules:
 *
 *  1. Risk-based override (wins over category):
 *     - riskClass === "high" OR legalReviewRequired === true → "heavy"
 *  2. Category-based default:
 *     - "tribunal_legal"     → "heavy"
 *     - "dispute"            → "medium"
 *     - "departure"          → "medium"
 *     - "performance_conduct" → "medium"
 *     - "leave"              → "light"
 *     - "compensation"       → "light"
 *     - "onboarding" / unknown → "light"
 *
 * The Edit page calls this on draft mount to decide whether to auto-pin
 * the evidence drawer ("heavy"), show a subtle prompt ("medium"), or
 * stay out of the way ("light").
 */
export function getEvidenceTier(template: Pick<LetterTemplate, "letterType" | "evidenceTier">): EvidenceTier {
  if (template.evidenceTier) return template.evidenceTier;
  return deriveEvidenceTier(template.letterType);
}

/**
 * Derivation logic exposed for callers that have a letter type but no
 * resolved template (e.g. when there's no template registered for a
 * given jurisdiction and the prompt builder falls back). The rules
 * mirror `getEvidenceTier`'s default branch.
 */
export function deriveEvidenceTier(letterType: LetterTypeId): EvidenceTier {
  const meta = getLetterMeta(letterType);
  if (meta.riskClass === "high" || meta.legalReviewRequired) return "heavy";
  switch (meta.category) {
    case "tribunal_legal":
      return "heavy";
    case "dispute":
    case "departure":
    case "performance_conduct":
      return "medium";
    case "leave":
    case "compensation":
    case "onboarding":
      return "light";
    default:
      return "light";
  }
}

